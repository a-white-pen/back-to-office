def ensure_review_status(conn, *, create=False):
    """Explicitly create or verify owner state; sorting setup never requires it."""
    with conn.transaction():
        conn.execute("SET LOCAL lock_timeout = '5s'")
        conn.execute("SET LOCAL statement_timeout = '15s'")
        exists = conn.execute("SELECT to_regclass('job_tracking.review_status')").fetchone()[0]
        if not exists and create:
            conn.execute("CREATE SCHEMA IF NOT EXISTS job_tracking")
            conn.execute(REVIEW_DDL)
        columns = conn.execute("""SELECT a.attname,format_type(a.atttypid,a.atttypmod),
            a.attnotnull,pg_get_expr(d.adbin,d.adrelid),a.attidentity
            FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
            JOIN pg_namespace n ON n.oid=c.relnamespace
            LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
            WHERE n.nspname='job_tracking' AND c.relname='review_status'
            AND a.attnum>0 AND NOT a.attisdropped ORDER BY a.attnum""").fetchall()
        if [(name, kind, required) for name, kind, required, _, _ in columns] != REVIEW_COLUMNS:
            raise ValueError("job_tracking.review_status: column contract differs")
        if any(
            default != ("now()" if name == "updated_at" else None) or identity
            for name, _, _, default, identity in columns
        ):
            raise ValueError("job_tracking.review_status: default/identity differs")
        constraints = conn.execute("""SELECT contype,pg_get_constraintdef(oid),convalidated
            FROM pg_constraint WHERE conrelid='job_tracking.review_status'::regclass
            AND contype <> 'n'""").fetchall()
        if constraints != [("p", "PRIMARY KEY (board, market, board_job_id)", True)]:
            raise ValueError("job_tracking.review_status: constraint contract differs")
        indexes = conn.execute("""SELECT indexdef FROM pg_indexes
            WHERE schemaname='job_tracking' AND tablename='review_status'""").fetchall()
        if (
            len(indexes) != 1
            or not indexes[0][0].startswith("CREATE UNIQUE INDEX")
            or not indexes[0][0].endswith(" USING btree (board, market, board_job_id)")
        ):
            raise ValueError("job_tracking.review_status: index contract differs")
        if conn.execute("""SELECT 1 FROM pg_trigger WHERE
            tgrelid='job_tracking.review_status'::regclass AND NOT tgisinternal""").fetchone():
            raise ValueError("job_tracking.review_status: unexpected trigger")


