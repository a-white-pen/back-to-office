def verify_job_sorting_tables(conn):
    """Refuse unknown contracts rather than silently repairing existing objects."""
    for table, expected in COLUMN_CONTRACT.items():
        schema = "costs" if table.startswith("gemini_") else "job_sorting"
        columns = conn.execute(
            """
            SELECT a.attname,format_type(a.atttypid,a.atttypmod),a.attnotnull,
                   pg_get_expr(d.adbin,d.adrelid),a.attidentity
            FROM pg_attribute a JOIN pg_class c ON c.oid=a.attrelid
            JOIN pg_namespace n ON n.oid=c.relnamespace
            LEFT JOIN pg_attrdef d ON d.adrelid=a.attrelid AND d.adnum=a.attnum
            WHERE n.nspname=%s AND c.relname=%s AND a.attnum>0 AND NOT a.attisdropped
            ORDER BY a.attnum""",
            (schema, table),
        ).fetchall()
        if [(r[0], r[1], r[2]) for r in columns] != expected:
            raise ValueError(f"{schema}.{table}: column contract differs")
        for name, _, _, default, identity in columns:
            expected_default = (
                "'{}'::jsonb"
                if name == "board_facts"
                else "now()"
                if name == "recorded_at"
                else None
            )
            if default != expected_default or identity != ("d" if name == "id" else ""):
                raise ValueError(f"{schema}.{table}.{name}: default/identity differs")
        constraints = conn.execute(
            """SELECT k.contype,pg_get_constraintdef(k.oid),k.convalidated
            FROM pg_constraint k JOIN pg_class c ON c.oid=k.conrelid
            JOIN pg_namespace n ON n.oid=c.relnamespace
            WHERE n.nspname=%s AND c.relname=%s AND k.contype <> 'n' """,
            (schema, table),
        ).fetchall()
        expected_types = (
            "ccccfffpu" if table == "job_listings" else "cp" if table.endswith("_results") else "p"
        )
        if "".join(sorted(r[0] for r in constraints)) != expected_types or not all(
            r[2] for r in constraints
        ):
            raise ValueError(f"{schema}.{table}: constraint contract differs")
        definitions = [r[1] for r in constraints]
        primary = (
            "id"
            if table == "job_listings"
            else "input_hash"
            if table.endswith("_results")
            else "gemini_response_id"
        )
        if f"PRIMARY KEY ({primary})" not in definitions:
            raise ValueError(f"{schema}.{table}: primary key differs")
        required = []
        allowed = {}
        if table == "job_listings":
            required = [
                "UNIQUE (board, market, board_job_id, wording_hash)",
                "FOREIGN KEY (triage_input_hash) REFERENCES job_sorting.triage_results(input_hash)",
                "FOREIGN KEY (extraction_input_hash) REFERENCES job_sorting.extraction_results(input_hash)",
                "FOREIGN KEY (repeat_of_id) REFERENCES job_sorting.job_listings(id)",
                "CHECK ((jsonb_typeof(board_facts) = 'object'::text))",
                "CHECK ((repeat_of_id <> id))",
            ]
            allowed = {
                "bucket": [
                    "top_picks",
                    "in_lane",
                    "less_interested",
                    "ineligible",
                    "not_sorted",
                    "title_filter",
                    "non_tech",
                    "tech_not_for_me",
                ],
                "decided_by": ["rules", "triage"],
            }
        elif table == "triage_results":
            allowed = {
                "verdict": [
                    "not_english",
                    "one_package",
                    "chip_or_electronics_design",
                    "research_publication",
                    "pass",
                    "non_tech",
                ]
            }
        elif table == "extraction_results":
            required = ["CHECK ((jsonb_typeof(lines) = 'array'::text))"]
        if not all(value in definitions for value in required):
            raise ValueError(f"{schema}.{table}: constraint definition differs")
        for column, values in allowed.items():
            checks = [
                d
                for kind, d, _ in constraints
                if kind == "c" and re.search(r"\b" + column + r"\b", d)
            ]
            if (
                len(checks) != 1
                or re.findall(r"'([^']*)'::text", checks[0]) != values
                or not checks[0].startswith(f"CHECK (({column} = ANY (ARRAY[")
            ):
                raise ValueError(f"{schema}.{table}: allowed values differ")
        indexes = conn.execute(
            "SELECT indexdef FROM pg_indexes WHERE schemaname=%s AND tablename=%s", (schema, table)
        ).fetchall()
        expected_indexes = (
            sorted(
                [
                    "(id)",
                    "(board, market, board_job_id, wording_hash)",
                    "(canonical_job_id)",
                    "(advertiser_name)",
                ]
            )
            if table == "job_listings"
            else [f"({primary})"]
        )
        if sorted(r[0].split(" USING btree ")[-1] for r in indexes) != expected_indexes:
            raise ValueError(f"{schema}.{table}: indexes differ")
        if sum(r[0].startswith("CREATE UNIQUE INDEX") for r in indexes) != (
            2 if table == "job_listings" else 1
        ):
            raise ValueError(f"{schema}.{table}: index uniqueness differs")


def ensure_job_sorting_tables(conn, *, create=False):
    with conn.transaction():
        conn.execute("SET LOCAL lock_timeout = '5s'")
        conn.execute("SET LOCAL statement_timeout = '15s'")
        names = [
            f"{'costs' if t.startswith('gemini_') else 'job_sorting'}.{t}" for t in COLUMN_CONTRACT
        ]
        existing = [conn.execute("SELECT to_regclass(%s)", (name,)).fetchone()[0] for name in names]
        if not any(existing) and create:
            if conn.execute("SELECT 1 FROM pg_namespace WHERE nspname='job_sorting'").fetchone():
                raise ValueError("Unexpected existing job_sorting schema")
            if not conn.execute("SELECT 1 FROM pg_namespace WHERE nspname='costs'").fetchone():
                raise ValueError("The existing costs schema is required")
            conn.execute(DDL)
        verify_job_sorting_tables(conn)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--create", action="store_true", help="Explicitly create absent contracts")
    args = parser.parse_args()
    from bto.settings import load_postgres

    load_postgres()
    with connect() as conn:
        ensure_job_sorting_tables(conn, create=args.create)
    print("Job-sorting contracts verified")


if __name__ == "__main__":
    main()
