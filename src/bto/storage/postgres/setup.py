def verify_job_research_tables(conn):
    """Verify research columns, defaults, constraints and indexes without repairs."""
    problems = []
    for table, expected_columns in JOB_RESEARCH_COLUMNS.items():
        schema, name = table.split(".")
        if conn.execute("SELECT to_regclass(%s)", (table,)).fetchone()[0] is None:
            problems.append(f"{table} is missing")
            continue
        found = {
            column: (kind, required, default, identity)
            for column, kind, required, default, identity in conn.execute(
                """SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
                       pg_get_expr(d.adbin, d.adrelid), a.attidentity
                FROM pg_attribute a JOIN pg_class c ON c.oid = a.attrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
                WHERE n.nspname = %s AND c.relname = %s AND a.attnum > 0
                AND NOT a.attisdropped ORDER BY a.attnum""",
                (schema, name),
            ).fetchall()
        }
        defaults = JOB_RESEARCH_DEFAULTS.get(table, {})
        for column, kind, required in expected_columns:
            if column not in found:
                problems.append(f"{table}.{column} is missing")
                continue
            found_kind, found_required, default, identity = found.pop(column)
            if found_kind != kind:
                problems.append(f"{table}.{column} is {found_kind}, not {kind}")
            if found_required != required:
                rule = "NOT NULL" if required else "nullable"
                problems.append(f"{table}.{column} should be {rule}")
            # attidentity is 'd' for GENERATED BY DEFAULT, 'a' for GENERATED ALWAYS
            # and empty for an ordinary column.
            if identity == "d":
                found_default = GENERATED_IDENTITY
            elif identity == "a":
                found_default = "generated always as identity"
            else:
                found_default = default
            expected_default = defaults.get(column)
            if found_default != expected_default:
                problems.append(
                    f"{table}.{column} default is {found_default or 'none'}, "
                    f"not {expected_default or 'none'}"
                )
        problems.extend(f"{table}.{column} is not in the data dictionary" for column in found)

        # NOT NULL rules are checked with the columns; PostgreSQL 18 also lists
        # them here as contype 'n'.
        definitions = [
            definition
            for (definition,) in conn.execute(
                """SELECT pg_get_constraintdef(k.oid) FROM pg_constraint k
                JOIN pg_class c ON c.oid = k.conrelid
                JOIN pg_namespace n ON n.oid = c.relnamespace
                WHERE n.nspname = %s AND c.relname = %s AND k.contype <> 'n'""",
                (schema, name),
            ).fetchall()
        ]
        expected_constraints = JOB_RESEARCH_CONSTRAINTS[table]
        expected_counts = Counter(expected_constraints)
        found_counts = Counter(definitions)
        problems.extend(
            f"{table} lacks {definition}"
            for definition in (expected_counts - found_counts).elements()
        )
        problems.extend(
            f"{table} has {definition}, which is not in the data dictionary"
            for definition in (found_counts - expected_counts).elements()
        )

        indexes = [
            definition
            for (definition,) in conn.execute(
                "SELECT indexdef FROM pg_indexes WHERE schemaname = %s AND tablename = %s",
                (schema, name),
            ).fetchall()
        ]
        primary_key_columns = expected_constraints[0].removeprefix("PRIMARY KEY ")
        if (
            len(indexes) != 1
            or not indexes[0].startswith("CREATE UNIQUE INDEX")
            or not indexes[0].endswith(f" USING btree {primary_key_columns}")
        ):
            problems.append(f"{table} should have only its primary key index, has {indexes}")
    if problems:
        raise ValueError(
            "Job-listing research and contact-finding tables differ from the data "
            "dictionary: " + "; ".join(problems)
        )


def ensure_job_research_tables(conn, *, create=False):
    """Create research tables only when requested, then verify all ten contracts.

    Review state must already exist because the research rows reference its anchors."""
    with conn.transaction():
        conn.execute("SET LOCAL lock_timeout = '5s'")
        conn.execute("SET LOCAL statement_timeout = '15s'")
        if create:
            if not conn.execute("SELECT 1 FROM pg_namespace WHERE nspname = 'costs'").fetchone():
                raise ValueError("The existing costs schema is required")
            review_status = conn.execute("SELECT to_regclass('job_tracking.review_status')")
            if review_status.fetchone()[0] is None:
                raise ValueError(
                    "job_tracking.review_status is required first; "
                    "create it with `python -m bto.storage.postgres.setup --review --create`"
                )
            conn.execute(JOB_RESEARCH_DDL)
        verify_job_research_tables(conn)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--create", action="store_true", help="Explicitly create absent contracts")
    parser.add_argument(
        "--review", action="store_true", help="Check/create only the Review state contract"
    )
    args = parser.parse_args()
    from bto.settings import load_postgres

    load_postgres()
    with connect() as conn:
        if args.review:
            ensure_review_status(conn, create=args.create)
        else:
            ensure_job_sorting_tables(conn, create=args.create)
    print("Review contract verified" if args.review else "Job-sorting contracts verified")


if __name__ == "__main__":
    main()
