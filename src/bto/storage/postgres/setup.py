def _format_allowed_values_check(column, values):
    """The CHECK `column IN (values)` as PostgreSQL prints it back."""
    listed = ", ".join(f"'{value}'::text" for value in values)
    return f"CHECK (({column} = ANY (ARRAY[{listed}])))"


def _format_json_array_check(column):
    """The CHECK that `column` holds a JSON array, as PostgreSQL prints it back."""
    return f"CHECK ((jsonb_typeof({column}) = 'array'::text))"


